public class Types {
    public static void main(String[] args) {
        int num1 = 9;
        byte b = 18;
        short s = 89;
        long l = 145555555L;
        System.out.println(num1 + b + s + l);

        float marks = 15.6f;
        double perc = 88.9999999999; //default
        System.out.println(marks);
        System.out.println(perc);

        char c = 'U'; //single-quotes
        //UNICODE
        System.out.println(c);

        boolean bool = true;
        System.out.println(bool);
    }
}
