package com.Collections.WrapperClasses;

public class Autoboxing {
    static void main(String[] args) {
        //autoboxing, automatic conversion of primitive to its corresponding wrapper class objects
        Double db = 55.5;

        Float fl = Float.valueOf(55.5f);
        float newFl = fl;
        //unboxing, automatic conversion of wrapper class objects back to its respective primitive type
    }
}
