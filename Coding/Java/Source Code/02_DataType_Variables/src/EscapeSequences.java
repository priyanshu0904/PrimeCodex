public class EscapeSequences {
    public static void main(String[] args){
        System.out.println("Hello\nPriyanshu"); //new line
        System.out.println("Hello\tPriyanshu"); //tab space
        System.out.println("Helloj\bPriyanshu"); //backspace
        System.out.println("Hello \"Priyanshu\""); //double quote
        System.out.println("Hello \\Priyanshu\\"); //backslash
        System.out.println("\'Hello\' Priyanshu"); //single quote
    }
}
